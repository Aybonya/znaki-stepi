    if (meta) meta.content = lang === 'kk' ? HTML_KK.desc : ruDesc;

    document.querySelectorAll('[data-i18n], [data-i18n-title], [data-i18n-aria]').forEach(el => {
      if (!ru.has(el)) ru.set(el, { html: el.innerHTML, title: el.getAttribute('title'), 'aria-label': el.getAttribute('aria-label') });
      const orig = ru.get(el);
      ATTRS.forEach(([key, attr]) => {
        const k = el.dataset[key];
        if (!k) return;
        const v = lang === 'kk' && HTML_KK[k] !== undefined ? HTML_KK[k] : orig[attr || 'html'];
        if (attr) el.setAttribute(attr, v); else el.innerHTML = v;
      });
    });
    document.querySelectorAll('[data-lang]').forEach(b => {
      b.classList.toggle('on', b.dataset.lang === lang);
      b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
    });
